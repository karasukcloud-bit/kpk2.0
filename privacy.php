        <li>сессионные cookie сервера организации — для сохранения авторизации во встроенном WebView;</li>
        <li>локальный PIN-код устройства — хранится только на устройстве в виде криптографического хеша (не передаётся на сервер);</li>
        <li>признак использования биометрии устройства — только локально;</li>
        <li>адрес сервера, указанный пользователем — локально на устройстве;</li>
        <li>расписания локальных уведомлений, загружаемые с сервера организации.</li>
    </ul>

    <h2>3. Цели обработки</h2>
    <ul>
        <li>доступ к системе учёта посещаемости и успеваемости;</li>
        <li>защита доступа к приложению на устройстве (PIN / биометрия);</li>
        <li>локальные напоминания по расписанию, заданному администратором.</li>
    </ul>

    <h2>4. Передача третьим лицам</h2>
